/*
 * Builds the PAHAD+ Android app (org.pahad.plus), signed with PAHAD's release key.
 *
 *   node scripts/build-android.js            # real build, data from https://pahad.org
 *   PAHAD_API_BASE=http://10.0.2.2:3006 node scripts/build-android.js   # test build against a local server (emulator)
 *
 * Makes, in mobile/pahad-plus/dist (never committed):
 *   PAHAD-Plus.apk   install on a phone to test
 *   PAHAD-Plus.aab   upload to Google Play
 *
 * Needs Java 17, the Android SDK, and the PAHAD signing key folder (pahad-release.keystore + keystore-password.txt,
 * alias "pahad"): by default C:\Users\<you>\pahad-apk, or set PAHAD_KEY_DIR. The password is read from the file and
 * never printed. Raise android.versionCode in app.json for every Play Store release.
 */
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "dist");
const HOME = process.env.USERPROFILE || process.env.HOME;
const WIN = process.platform === "win32";
const KEY_DIR = process.env.PAHAD_KEY_DIR || path.join(HOME, "pahad-apk");
const KEYSTORE = path.join(KEY_DIR, "pahad-release.keystore");
const PASSWORD_FILE = path.join(KEY_DIR, "keystore-password.txt");

const LOCAL = process.env.LOCALAPPDATA || path.join(HOME, "AppData", "Local");
const SDK = [process.env.ANDROID_HOME, process.env.ANDROID_SDK_ROOT, "D:\\Dev\\Android\\Sdk", path.join(LOCAL, "Android", "Sdk")]
  .find((p) => p && fs.existsSync(path.join(p, "build-tools")));
const jdkIn = (dir) => { try { return fs.readdirSync(dir).filter((n) => /^(jdk-?)?17/i.test(n)).map((n) => path.join(dir, n)); } catch { return []; } };
const exe = (name) => (WIN ? `${name}.exe` : name);
const JDK = [process.env.JAVA_HOME, ...jdkIn(path.join(HOME, ".jdks")), ...jdkIn("C:\\Program Files\\Java"), ...jdkIn("C:\\Program Files\\Eclipse Adoptium")]
  .find((p) => p && fs.existsSync(path.join(p, "bin", exe("java"))));

function fail(msg) { console.error(`\n✕ ${msg}`); process.exit(1); }
if (!SDK) fail("Android SDK not found. Set ANDROID_HOME.");
if (!JDK) fail("Java 17 not found. Set JAVA_HOME.");
for (const f of [KEYSTORE, PASSWORD_FILE]) if (!fs.existsSync(f)) fail(`Missing ${f}. Set PAHAD_KEY_DIR to the folder with the PAHAD signing key.`);

const tmp = WIN ? "D:/apktmp" : "/tmp/pahad-apk";
fs.mkdirSync(tmp, { recursive: true });
fs.mkdirSync(OUT, { recursive: true });
const env = {
  ...process.env, JAVA_HOME: JDK, ANDROID_HOME: SDK, ANDROID_SDK_ROOT: SDK, NODE_ENV: "production", CI: "1",
  // Gradle on Windows can fail with "Unable to establish loopback connection" when the temp path has spaces.
  JAVA_TOOL_OPTIONS: `-Djdk.net.unixdomain.tmpdir=${tmp} -Djava.io.tmpdir=${tmp}`,
  PAHAD_KEYSTORE: KEYSTORE,
  PAHAD_KS: fs.readFileSync(PASSWORD_FILE, "utf8").trim(),
};

function run(cmd, args, cwd, label) {
  console.log(`\n▶ ${label}`);
  const r = spawnSync(cmd, args, { cwd, env, stdio: "inherit", shell: WIN && cmd.endsWith(".cmd") });
  if (r.status !== 0) fail(`${label} failed (${r.status}).`);
}

console.log(`Android SDK: ${SDK}\nJava: ${JDK}\nData from: ${process.env.PAHAD_API_BASE || "https://pahad.org"}`);
// Windows limits paths to 260 characters, and react-native-reanimated's native build goes over that from a deep
// folder. On Windows the app is copied to a short build folder (PAHAD_BUILD_DIR, default D:\pp) and built there.
// (A drive letter made with `subst` doesn't help: Node resolves packages back to the long real path.)
let BUILD = ROOT;
if (WIN && ROOT.length > 12) {
  BUILD = process.env.PAHAD_BUILD_DIR || "D:\\pp";
  fs.mkdirSync(BUILD, { recursive: true });
  const skip = new Set(["node_modules", "android", "ios", ".expo", "dist"]);
  for (const name of fs.readdirSync(ROOT)) {
    if (skip.has(name)) continue;
    fs.cpSync(path.join(ROOT, name), path.join(BUILD, name), { recursive: true, force: true });
  }
  const lock = (dir) => { try { return fs.readFileSync(path.join(dir, "package-lock.json"), "utf8"); } catch { return ""; } };
  const installed = path.join(BUILD, "node_modules", ".pahad-lock");
  if (!fs.existsSync(installed) || fs.readFileSync(installed, "utf8") !== lock(ROOT)) {
    run("npm.cmd", ["ci", "--no-audit", "--no-fund", "--legacy-peer-deps"], BUILD, `Installing packages in ${BUILD}`);
    fs.writeFileSync(installed, lock(ROOT));
  }
}

run(WIN ? "npx.cmd" : "npx", ["expo", "prebuild", "--platform", "android", "--clean", "--no-install"], BUILD, "Generating the Android project");

const android = path.join(BUILD, "android");
fs.writeFileSync(path.join(android, "local.properties"), `sdk.dir=${SDK.split(path.sep).join("/")}\n`);

// Release builds are signed with PAHAD's key (the same key as the earlier PAHAD+ app, so this installs over it).
// android/ is generated by prebuild and never committed, so it is patched here on every build.
const gradleFile = path.join(android, "app", "build.gradle");
let gradle = fs.readFileSync(gradleFile, "utf8");
const releaseSigning = [
  "signingConfigs {",
  "        release {",
  '            storeFile file(System.getenv("PAHAD_KEYSTORE"))',
  '            storePassword System.getenv("PAHAD_KS")',
  '            keyAlias "pahad"',
  '            keyPassword System.getenv("PAHAD_KS")',
  "        }",
].join("\n");
gradle = gradle.replace("signingConfigs {", releaseSigning);
const releaseBlock = gradle.indexOf("release {", gradle.indexOf("buildTypes {"));
const debugRef = gradle.indexOf("signingConfig signingConfigs.debug", releaseBlock);
if (releaseBlock < 0 || debugRef < 0) fail("Couldn't set up release signing in android/app/build.gradle.");
gradle = `${gradle.slice(0, debugRef)}signingConfig signingConfigs.release${gradle.slice(debugRef + "signingConfig signingConfigs.debug".length)}`;
// Windows: let CMake shorten long object-file paths (react-native-gesture-handler's codegen goes past 260 characters).
gradle = gradle.replace("    defaultConfig {", '    defaultConfig {\n        externalNativeBuild { cmake { arguments "-DCMAKE_OBJECT_PATH_MAX=128" } }');
fs.writeFileSync(gradleFile, gradle);

run(path.join(JDK, "bin", exe("java")), ["-cp", path.join(android, "gradle", "wrapper", "gradle-wrapper.jar"), "org.gradle.wrapper.GradleWrapperMain", "assembleRelease", "bundleRelease", "--no-daemon"], android, "Compiling (Gradle)");

const apk = path.join(OUT, "PAHAD-Plus.apk");
const aab = path.join(OUT, "PAHAD-Plus.aab");
fs.copyFileSync(path.join(android, "app", "build", "outputs", "apk", "release", "app-release.apk"), apk);
fs.copyFileSync(path.join(android, "app", "build", "outputs", "bundle", "release", "app-release.aab"), aab);
const buildTools = path.join(SDK, "build-tools", fs.readdirSync(path.join(SDK, "build-tools")).sort().pop());
run(path.join(JDK, "bin", exe("java")), ["-jar", path.join(buildTools, "lib", "apksigner.jar"), "verify", "--print-certs", apk], ROOT, "Checking the signature");

console.log(`\n✓ Built\n  ${apk}   ← install on a phone to test\n  ${aab}   ← upload to Google Play`);
